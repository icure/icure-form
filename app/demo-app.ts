	@state() private rendererMode: 'form:tab' | 'card' = 'form:tab'
	@state() private selectedSlug: string = this.initialSlug()
	@state() private expandedSpecialties: Set<string> = new Set()
	@state() private expandedSubforms: Set<string> = new Set()

	// Specialty forms are lazily imported on selection (there are hundreds of them, some
	// sizeable), so they're cached here rather than parsed up front like the YAML samples.
	private specialtyFormCache = new Map<string, Form>()
	private loadingSpecialtySlug?: string

	private initialSlug(): string {
		const fromHash = location.hash.replace(/^#/, '')
		if (this.samples?.find((s) => s.slug === fromHash) || this.resolveSpecialtyHash(fromHash)) {
			return fromHash
		}
		// `samples` isn't initialised yet when this runs from the field initialiser, and an
		// empty/unrecognised hash falls back to the first sample's slug.
		return '01-components-gallery'
	}

	private get currentFormElementId(): string | undefined {
		const sample = this.samples.find((s) => s.slug === this.selectedSlug)
		if (sample) {
			return sample.form.id ?? sample.form.form
		}
		const form = this.specialtyFormCache.get(this.selectedSlug)
		return form ? form.id ?? form.form : undefined
	}

	private resolveSpecialtyHash(slug: string): { specialty: string; file: string } | undefined {
		const slash = slug.indexOf('/')
		if (slash <= 0) {
			return undefined
		}
		const specialty = slug.slice(0, slash)
		const file = slug.slice(slash + 1)
		const match = SPECIALTY_INDEX[specialty]?.find((e) => fileStem(e.file) === file)
		return match ? { specialty, file } : undefined
	}

	private selectSample(slug: string) {
		this.selectedSlug = slug
		if (location.hash.replace(/^#/, '') !== slug) {
			history.replaceState(null, '', `#${slug}`)
		}
	}

	private selectSpecialtyForm(specialty: string, file: string) {
		const slug = `${specialty}/${file}`
		this.selectedSlug = slug
		if (location.hash.replace(/^#/, '') !== slug) {
			history.replaceState(null, '', `#${slug}`)
		}
		void this.loadSpecialtyForm(specialty, file)
	}

	private async loadSpecialtyForm(specialty: string, file: string): Promise<void> {
		const slug = `${specialty}/${file}`
		if (this.specialtyFormCache.has(slug)) {
			return
		}
		this.loadingSpecialtySlug = slug
		this.requestUpdate()
		try {
			const mod = (await import(`./samples/curated/${specialty}/${file}.json`)) as { default: unknown }
			this.specialtyFormCache.set(slug, Form.parse(mod.default as never))
		} finally {
			if (this.loadingSpecialtySlug === slug) {
				this.loadingSpecialtySlug = undefined
			}
			this.requestUpdate()
		}
	}

	private toggleSpecialty(specialty: string) {
		const next = new Set(this.expandedSpecialties)
		next.has(specialty) ? next.delete(specialty) : next.add(specialty)
		this.expandedSpecialties = next
	}

	private toggleSubforms(specialty: string) {
		const next = new Set(this.expandedSubforms)
		next.has(specialty) ? next.delete(specialty) : next.add(specialty)
		this.expandedSubforms = next
	}

	// Expands the tree down to whatever specialty form the hash points at, and starts
	// loading it — used both on direct hash navigation and on first mount.
	private revealSelection() {
		const resolved = this.resolveSpecialtyHash(this.selectedSlug)
		if (!resolved) {
			return
		}
		if (!this.expandedSpecialties.has(resolved.specialty)) {
			this.expandedSpecialties = new Set(this.expandedSpecialties).add(resolved.specialty)
		}
		const { subforms } = splitTopAndSubforms(SPECIALTY_INDEX[resolved.specialty] ?? [])
		if (subforms.some((e) => fileStem(e.file) === resolved.file) && !this.expandedSubforms.has(resolved.specialty)) {
			this.expandedSubforms = new Set(this.expandedSubforms).add(resolved.specialty)
		}
		void this.loadSpecialtyForm(resolved.specialty, resolved.file)
	}

	private onHashChange = () => {
		const slug = location.hash.replace(/^#/, '')
		if (slug && this.samples.find((s) => s.slug === slug)) {
			this.selectedSlug = slug
			return
		}
		if (slug && this.resolveSpecialtyHash(slug)) {
			this.selectedSlug = slug
			this.revealSelection()
		}
	}

