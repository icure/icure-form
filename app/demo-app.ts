// Generated by tools/convert-legacy/build-specialty-index.ts from app/samples/curated/
// (a git submodule: icure/speciality-forms).
type SpecialtyFormEntry = { file: string; id: string | null; title: string; embeds: string[] }
const SPECIALTY_INDEX = specialtyIndexJson as Record<string, SpecialtyFormEntry[]>

// A handful of the specialty slugs don't read well once the language suffix is stripped
// (e.g. "plasticandreparatorysurgery" has no word boundaries); override those, fall back
// to a simple capitalization for the rest.
const SPECIALTY_LABELS: Record<string, string> = {
	'nose-throat-ear': 'Nose, Throat & Ear',
	ophtalmology: 'Ophthalmology',
	orthopedy: 'Orthopedics',
	pediatry: 'Pediatrics',
	persphysician: 'General Practice',
	plasticandreparatorysurgery: 'Plastic & Reparatory Surgery',
}

function specialtyLabel(key: string): string {
	if (key.startsWith('common_')) {
		return 'Common'
	}
	const base = key.replace(/-(fr|nl|en)$/, '')
	return SPECIALTY_LABELS[base] ?? base.charAt(0).toUpperCase() + base.slice(1)
}

// Which specialty directories are in scope for the app's current language, common_* first.
function specialtiesForLanguage(lang: string): string[] {
	const commonKey = `common_${lang}`
	const suffix = `-${lang}`
	return Object.keys(SPECIALTY_INDEX)
		.filter((key) => key === commonKey || key.endsWith(suffix))
		.sort((a, b) => {
			const aCommon = a.startsWith('common_')
			const bCommon = b.startsWith('common_')
			return aCommon !== bCommon ? (aCommon ? -1 : 1) : a.localeCompare(b)
		})
}

// A form is a subform, rather than a top-level entry, if some other form in the same
// specialty directory embeds it (as a Subform.forms value) — regardless of whether that
// referencing form is itself still standalone after de-duplicating forms shared across
// specialties into common_fr/common_nl.
function splitTopAndSubforms(entries: SpecialtyFormEntry[]): { top: SpecialtyFormEntry[]; subforms: SpecialtyFormEntry[] } {
	const embedded = new Set<string>()
	entries.forEach((e) => e.embeds.forEach((id) => embedded.add(id)))
	const top: SpecialtyFormEntry[] = []
	const subforms: SpecialtyFormEntry[] = []
	entries.forEach((e) => (e.id && embedded.has(e.id) ? subforms : top).push(e))
	return { top, subforms }
}

function fileStem(file: string): string {
	return file.replace(/\.json$/, '')
}

