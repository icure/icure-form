	connectedCallback() {
		super.connectedCallback()
		// Sync once after construction in case the hash matched a slug only known after `samples`
		// was assigned; also expands the specialty tree and starts loading if it's a deep link.
		this.onHashChange()
		window.addEventListener('hashchange', this.onHashChange)
		window.onkeydown = (event) => {
			if ((event.key === 'Z' || event.key === 'z') && event.metaKey) {
				const target = this.shadowRoot?.getElementById(this.currentFormElementId ?? '')
				if (!target) {
					return
				}
				if (event.key === 'Z') {
					event.preventDefault()
					;(target as DecoratedForm).redo()
				} else if (event.key === 'z') {
					event.preventDefault()
					;(target as DecoratedForm).undo()
				}
			}
		}
	}

	disconnectedCallback() {
		window.removeEventListener('hashchange', this.onHashChange)
		super.disconnectedCallback()
	}

	private renderFormItem(specialty: string, entry: SpecialtyFormEntry) {
		const stem = fileStem(entry.file)
		const slug = `${specialty}/${stem}`
		const classes = slug === this.selectedSlug ? 'selected' : ''
		return html`
			<li class="${classes}" @click="${() => this.selectSpecialtyForm(specialty, stem)}">
				<span class="title">${entry.title}</span>
			</li>
		`
	}

	private renderSpecialty(specialty: string) {
		const { top, subforms } = splitTopAndSubforms(SPECIALTY_INDEX[specialty] ?? [])
		const isExpanded = this.expandedSpecialties.has(specialty)
		const subformsExpanded = this.expandedSubforms.has(specialty)
		return html`
			<li class="specialty">
				<div class="specialty-header" @click="${() => this.toggleSpecialty(specialty)}">
					<span class="chevron ${isExpanded ? 'open' : ''}">▸</span>
					<span>${specialtyLabel(specialty)}</span>
					<span class="count">${top.length + subforms.length}</span>
				</div>
				${isExpanded
					? html`
							<ul class="form-list">
								${top.map((e) => this.renderFormItem(specialty, e))}
							</ul>
							${subforms.length
								? html`
										<div class="subform-folder-header" @click="${() => this.toggleSubforms(specialty)}">
											<span class="chevron ${subformsExpanded ? 'open' : ''}">▸</span>
											<span>Subforms</span>
											<span class="count">${subforms.length}</span>
										</div>
										${subformsExpanded
											? html`<ul class="form-list subform-list">
													${subforms.map((e) => this.renderFormItem(specialty, e))}
											  </ul>`
											: ''}
								  `
								: ''}
					  `
					: ''}
			</li>
		`
	}

